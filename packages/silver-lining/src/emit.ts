import { type ThemeId, THEME_IDS, THEME_INPUTS, THEME_LABELS, buildThemes } from "./themes.ts";
import { type ThemeTokens, TOKEN_NAMES } from "./generator.ts";

export const SL_PREFIX = "--sl-";

/**
 * Names apps/web already used (Tailwind v4 `--color-*` theme variables) that
 * differ from the canonical token name. Emitted as aliases so existing
 * utilities and `var(--color-*)` call sites keep working.
 */
export const LEGACY_ALIASES: Record<string, string> = {
  "--color-urgent": "status-urgent",
  "--color-attention": "status-attention",
  "--color-healthy": "status-healthy",
  "--color-neutral": "status-neutral",
};

export const cssVarName = (token: string): string => `${SL_PREFIX}${token}`;

export function themeDeclarations(tokens: ThemeTokens, mode: "dark" | "light"): string[] {
  return [
    `color-scheme: ${mode};`,
    ...TOKEN_NAMES.map((name) => `${cssVarName(name)}: ${tokens[name]};`),
  ];
}

/** Inline-style map for applying a generated (custom) theme at runtime. */
export function themeToStyle(tokens: ThemeTokens, mode: "dark" | "light"): Record<string, string> {
  const style: Record<string, string> = { colorScheme: mode };
  for (const name of TOKEN_NAMES) style[cssVarName(name)] = tokens[name];
  return style;
}

const block = (selector: string, decls: string[]): string =>
  `${selector} {\n${decls.map((d) => `  ${d}`).join("\n")}\n}\n`;

export function buildCss(themes: Record<ThemeId, ThemeTokens> = buildThemes()): string {
  const decl = (id: ThemeId) => themeDeclarations(themes[id], THEME_INPUTS[id].mode);
  const aliases = [
    ...TOKEN_NAMES.map((n) => `--color-${n}: var(${cssVarName(n)});`).filter(
      (l) => !l.startsWith("--color-status-") && !l.endsWith("-soft);"),
    ),
    ...Object.entries(LEGACY_ALIASES).map(([a, t]) => `${a}: var(${cssVarName(t)});`),
  ];
  return [
    "/* Silver Lining tokens. GENERATED by packages/silver-lining (pnpm --filter @tallyline/silver-lining generate).",
    "   Do not edit by hand. Source of truth: docs/design/silver-lining.md sections 2, 3, 5. */",
    "",
    block(':root,\n:root[data-theme="dark"]', decl("dark")),
    `@media (prefers-color-scheme: light) {\n${block(":root:not([data-theme])", decl("light"))
      .split("\n")
      .map((l) => (l ? `  ${l}` : l))
      .join("\n")}}\n`,
    block(':root[data-theme="light"],\nhtml.light', decl("light")),
    block(':root[data-theme="hc-dark"]', decl("hc-dark")),
    "/* Aliases for names apps/web already used (Tailwind --color-*). */",
    block(":root", aliases),
  ].join("\n");
}

export function buildJson(themes: Record<ThemeId, ThemeTokens> = buildThemes()): string {
  const out = {
    name: "silver-lining",
    version: 1,
    themes: Object.fromEntries(
      THEME_IDS.map((id) => [
        id,
        {
          label: THEME_LABELS[id],
          mode: THEME_INPUTS[id].mode,
          inputs: {
            base: THEME_INPUTS[id].base,
            accent: THEME_INPUTS[id].accent,
            contrast: THEME_INPUTS[id].contrast,
          },
          tokens: themes[id],
        },
      ]),
    ),
  };
  return `${JSON.stringify(out, null, 2)}\n`;
}

export function buildTs(themes: Record<ThemeId, ThemeTokens> = buildThemes()): string {
  return [
    "// GENERATED by packages/silver-lining (pnpm --filter @tallyline/silver-lining generate). Do not edit.",
    "",
    `export const tokens = ${JSON.stringify(themes, null, 2)} as const;`,
    "",
    "export type GeneratedThemeId = keyof typeof tokens;",
    "",
  ].join("\n");
}
